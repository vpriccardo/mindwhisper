def build_rows() -> list[dict]:
    by_id: dict[str, dict] = {}
    for raw_canon, themes, aliases, weight in CATALOG:
        features = analyze(raw_canon)
        canonical = features["word"]
        cid = concept_id_for(canonical)
        theme_set = {t.strip() for t in themes.split("|") if t.strip()}
        alias_set = {normalize_word(a) for a in aliases.split("|") if a.strip()}
        alias_set.discard(canonical)
        if cid in by_id:
            existing = by_id[cid]
            merged_themes = set(existing["themes"].split("|")) | theme_set
            existing["themes"] = "|".join(sorted(merged_themes))
            existing_aliases = set(existing["aliases"].split("|")) if existing["aliases"] else set()
            existing_aliases |= alias_set
            existing_aliases.discard(canonical)
            existing["aliases"] = "|".join(sorted(existing_aliases))
            existing["base_weight"] = max(int(existing["base_weight"]), int(weight))
            continue
        by_id[cid] = {
            "concept_id": cid,
            "canonical_word": canonical,
            "aliases": "|".join(sorted(alias_set)),
            "language": "it",
            "themes": "|".join(sorted(theme_set)),
            "base_weight": int(weight),
            **{k: v for k, v in features.items() if k != "word"},
        }
    return [by_id[k] for k in sorted(by_id)]



def find_suspect_pairs(rows: list[dict]) -> list[tuple[str, str, str]]:
    """Heuristic synonym collisions for manual review — not auto-merged."""
    words = [r["canonical_word"] for r in rows]
    word_set = set(words)
    suspects: list[tuple[str, str, str]] = []
    seen: set[tuple[str, str]] = set()

    def add(a: str, b: str, reason: str) -> None:
        key = tuple(sorted((a, b)))
        if key in seen or a == b:
            return
        seen.add(key)
        suspects.append((a, b, reason))

    # Known explicit merges already applied — still list for review visibility
    known = [
        ("COLAPASTA", "SCOLAPASTA", "prefix_s_variant"),
        ("FRIGORIFERO", "FRIGO", "abbreviation"),
        ("TELEVISORE", "TV", "abbreviation"),
        ("TELEVISORE", "TELEVISIONE", "near_synonym"),
        ("SEDIA", "SEGGIOLA", "regional_synonym"),
    ]
    for a, b, reason in known:
        add(a, b, reason)

    diminutive_suffixes = ("INO", "INA", "ETTO", "ETTA", "ELLO", "ELLA", "UCCIO", "UCIA")
    for w in words:
        if w.startswith("S") and len(w) > 4 and w[1:] in word_set:
            add(w[1:], w, "prefix_s_variant")
        for suf in diminutive_suffixes:
            if w.endswith(suf) and len(w) > len(suf) + 2:
                stem = w[: -len(suf)]
                for other in words:
                    if other != w and (other == stem or other.startswith(stem) and abs(len(other) - len(stem)) <= 2):
                        if other.startswith(stem[:4]):
                            add(w, other, "diminutive_or_stem")
                            break
        # short abbreviation: shorter word is prefix of longer (len <= 4)
        if len(w) <= 5:
            for other in words:
                if other != w and other.startswith(w) and len(other) >= len(w) + 3:
                    add(w, other, "possible_abbreviation")
    return sorted(suspects)


def quality_report(rows: list[dict], suspects: list[tuple[str, str, str]]) -> None:
    theme_counts: Counter[str] = Counter()
    alias_count = 0
    lengths = []
    canon_words = [r["canonical_word"] for r in rows]
    for r in rows:
        lengths.append(int(r["length"]))
        alias_count += len([a for a in r["aliases"].split("|") if a])
        for t in r["themes"].split("|"):
            if t:
                theme_counts[t] += 1
    dupes = [w for w, n in Counter(canon_words).items() if n > 1]
    print("=== Dictionary quality report ===")
    print(f"Total canonical concepts: {len(rows)}")
    print(f"Total aliases: {alias_count}")
    print("Concepts per theme:")
    for t in sorted(theme_counts):
        print(f"  {t}: {theme_counts[t]}")
    print(f"Average word length: {sum(lengths)/len(lengths):.2f}")
    print(f"Duplicate canonical words: {len(dupes)}" + (f" {dupes[:10]}" if dupes else ""))
    print(f"Potential synonym collisions (review): {len(suspects)}")
    weight_counts = Counter(int(r["base_weight"]) for r in rows)
    print("Weight classes:")
    for w in sorted(weight_counts, reverse=True):
        print(f"  {WEIGHT_CLASS.get(w, w)}={w}: {weight_counts[w]}")


def main() -> None:
    rows = build_rows()
    if not (1000 <= len(rows) <= 2500):
        raise SystemExit(f"Dictionary size {len(rows)} outside target 1000-2500")
    suspects = find_suspect_pairs(rows)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=FIELDNAMES)
        writer.writeheader()
        for row in rows:
            out = dict(row)
            out["starts_with_vowel"] = str(bool(row["starts_with_vowel"])).lower()
            out["ends_with_vowel"] = str(bool(row["ends_with_vowel"])).lower()
            out["double_letter"] = str(bool(row["double_letter"])).lower()
            writer.writerow(out)
    with REVIEW_OUT.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=["word_a", "word_b", "reason"])
        writer.writeheader()
        for a, b, reason in suspects:
            writer.writerow({"word_a": a, "word_b": b, "reason": reason})
    quality_report(rows, suspects)
    print(f"Wrote {len(rows)} concepts to {OUT}")
    print(f"Wrote {len(suspects)} review pairs to {REVIEW_OUT}")


if __name__ == "__main__":
    main()
