def normalize_word(word: str) -> str:
    """Strip accents, uppercase, keep A-Z only."""
    decomposed = unicodedata.normalize("NFKD", word.strip())
    ascii_only = "".join(ch for ch in decomposed if not unicodedata.combining(ch))
    return "".join(ch for ch in ascii_only.upper() if "A" <= ch <= "Z")


def has_double_letter(letters: str) -> bool:
    return any(letters[i] == letters[i + 1] for i in range(len(letters) - 1))


def analyze(word: str) -> dict:
    letters = normalize_word(word)
    if not letters:
        raise ValueError(f"empty word after normalize: {word!r}")
    vowel_positions = [i + 1 for i, ch in enumerate(letters) if ch in VOWELS]
    consonant_positions = [i + 1 for i, ch in enumerate(letters) if ch not in VOWELS]
    length = len(letters)
    internal_vowel_count = sum(1 for p in vowel_positions if p != 1 and p != length)
    return {
        "word": letters,
        "length": length,
        "vowel_count": len(vowel_positions),
        "consonant_count": len(consonant_positions),
        "internal_vowel_count": internal_vowel_count,
        "starts_with_vowel": letters[0] in VOWELS,
        "ends_with_vowel": letters[-1] in VOWELS,
        "vowel_positions": "|".join(str(p) for p in vowel_positions),
        "consonant_positions": "|".join(str(p) for p in consonant_positions),
        "vowel_sequence": "|".join(letters[p - 1] for p in vowel_positions),
        "first_letter": letters[0],
        "last_letter": letters[-1],
        "double_letter": has_double_letter(letters),
    }


def concept_id_for(canonical: str) -> str:
    return normalize_word(canonical).lower()


